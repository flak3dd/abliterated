#!/usr/bin/env bash
# ==============================================================================
# ABLITERATED // SKULL VORTEX TERMINAL ANIMATION
# Seamless 14-frame holographic skull disintegration & reconstitution loop
# With integrated Matrix digital rain effect
# ==============================================================================

set -e

# Terminal state tracking
IN_ALT_SCREEN=0
CURSOR_HIDDEN=0
CLEANED_UP=0

cleanup() {
  if [ "$CLEANED_UP" -eq 1 ]; then return; fi
  CLEANED_UP=1
  printf "\033[0m\033[?7h\033[?25h"
  if [ "$IN_ALT_SCREEN" -eq 1 ]; then
    printf "\033[?1049l"
  fi
  printf "\n"
  exit 0
}

trap cleanup INT TERM EXIT

# Usage manual
show_help() {
  cat << 'HELP_EOF'
ABLITERATED SKULL VORTEX // Terminal Animation with Matrix Rain

USAGE:
  ./skull.sh [OPTIONS]

OPTIONS:
  -c, --color <name>    Color theme:
                          cyan / electric (default) - Abliterated cyber cyan
                          matrix / green - Phosphor green Matrix style
                          blue      - Deep cobalt blue
                          crimson   - Blood red
                          synthwave - Neon magenta / violet
                          amber     - Golden amber
                          rainbow   - Dynamic cycling hues
                          mono      - Raw monochrome ASCII
      --rain            Enable Matrix digital rain (default: enabled)
      --no-rain         Disable Matrix digital rain (skull only)
      --matrix          Preset: Matrix theme with falling digital rain
  -f, --fps <num>       Frames per second (default: 12)
  -d, --delay <sec>     Sleep seconds per frame (default: 0.08)
  -m, --mode <mode>     Animation mode:
                          loop    (default) - Continuous 1->14 rotation
                          bounce  - Ping-pong 1->14->1 oscillation
                          once    - Play 1 full cycle and exit
      --full            Force full 65-line mode (requires 67+ rows)
      --no-hud          Hide bottom status HUD
  -h, --help            Display this help manual

INTERACTIVE KEYS (while playing):
  q, Q, ESC             Quit
  r, R                  Toggle Matrix digital rain On / Off
  g, G                  Toggle Matrix Green / Cyber Cyan theme
  c, C                  Cycle through all color palettes
  b, B                  Toggle bounce / loop mode
  +, =                  Increase speed (higher FPS)
  -, _                  Decrease speed (lower FPS)
  h, H                  Toggle bottom status HUD
  SPACE                 Pause / Resume animation

HELP_EOF
  exit 0
}

# Configuration
FPS=12
DELAY="0.08"
COLOR_THEME="cyan"
MODE="loop"
SHOW_HUD=1
FORCE_FULL=0
RAIN_ENABLED=1

ESC=$'\033'
RESET="${ESC}[0m"

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      -c|--color)
        COLOR_THEME="${2:-cyan}"
        shift 2
        ;;
      --matrix)
        COLOR_THEME="matrix"
        RAIN_ENABLED=1
        shift
        ;;
      --rain)
        RAIN_ENABLED=1
        shift
        ;;
      --no-rain)
        RAIN_ENABLED=0
        shift
        ;;
      -f|--fps)
        FPS="${2:-12}"
        DELAY=$(awk "BEGIN { printf \"%.3f\", 1.0 / $FPS }" 2>/dev/null || echo "0.08")
        shift 2
        ;;
      -d|--delay)
        DELAY="${2:-0.08}"
        shift 2
        ;;
      -m|--mode)
        MODE="${2:-loop}"
        shift 2
        ;;
      --loop)
        MODE="loop"
        shift
        ;;
      --bounce)
        MODE="bounce"
        shift
        ;;
      --once)
        MODE="once"
        shift
        ;;
      --full)
        FORCE_FULL=1
        shift
        ;;
      --no-hud)
        SHOW_HUD=0
        shift
        ;;
      --hud)
        SHOW_HUD=1
        shift
        ;;
      -h|--help)
        show_help
        ;;
      *)
        shift
        ;;
    esac
  done
}

update_dimensions() {
  ROWS=$(tput lines 2>/dev/null || true)
  [ -z "$ROWS" ] || [ "$ROWS" -le 0 ] && ROWS=${LINES:-24}
  COLS=$(tput cols 2>/dev/null || true)
  [ -z "$COLS" ] || [ "$COLS" -le 0 ] && COLS=${COLUMNS:-80}

  if [ "$FORCE_FULL" -eq 1 ]; then
    MAX_ROWS=65
  else
    MAX_ROWS=$(( ROWS - 2 ))
    [ "$MAX_ROWS" -lt 6 ] && MAX_ROWS=6
    [ "$MAX_ROWS" -gt 65 ] && MAX_ROWS=65
  fi
}

declare -a RAW_FRAMES=()
load_raw_frames() {
  RAW_FRAMES=()
  local all_data
  all_data=$(get_raw_skull_data)
  local f=0
  local l=0
  local buf=""
  local line

  while IFS= read -r line || [ -n "$line" ]; do
    if [ $l -eq 0 ]; then
      buf="$line"
    else
      buf="$buf"$'\n'"$line"
    fi
    l=$((l + 1))
    if [ $l -eq 65 ]; then
      RAW_FRAMES[$f]="$buf"
      f=$((f + 1))
      buf=""
      l=0
    fi
  done <<< "$all_data"
}

render_skull_matrix() {
  local frame_idx="$1"
  local step="$2"

  printf "\033[1;1H"
  awk -v max_rows="$MAX_ROWS" \
      -v cols="$COLS" \
      -v step="$step" \
      -v rain="$RAIN_ENABLED" \
      -v theme="$COLOR_THEME" '
  BEGIN {
    reset = "\033[0m"
    glyphs = "ｦｱｳｴｵｶｷｹｺｻｼｽｾｿﾀﾂﾃﾅﾆﾇﾈﾊﾋﾎﾏﾐﾑﾒﾓﾔﾕﾗﾘﾜ0123456789ABCDEF$#*+-=<>:."
    g_len = length(glyphs)

    if (theme == "matrix" || theme == "green") {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;46m"
      r_med   = "\033[38;5;40m"
      r_dim   = "\033[38;5;28m"
      r_faint = "\033[38;5;22m"
    } else if (theme == "crimson" || theme == "red") {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;196m"
      r_med   = "\033[38;5;160m"
      r_dim   = "\033[38;5;124m"
      r_faint = "\033[38;5;88m"
    } else if (theme == "synthwave" || theme == "purple") {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;201m"
      r_med   = "\033[38;5;165m"
      r_dim   = "\033[38;5;129m"
      r_faint = "\033[38;5;93m"
    } else if (theme == "amber" || theme == "gold") {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;214m"
      r_med   = "\033[38;5;208m"
      r_dim   = "\033[38;5;172m"
      r_faint = "\033[38;5;130m"
    } else if (theme == "cobalt" || theme == "blue") {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;39m"
      r_med   = "\033[38;5;33m"
      r_dim   = "\033[38;5;27m"
      r_faint = "\033[38;5;21m"
    } else if (theme == "mono") {
      r_head  = ""
      r_hi    = ""
      r_med   = ""
      r_dim   = ""
      r_faint = ""
    } else {
      r_head  = "\033[1;38;5;15m"
      r_hi    = "\033[1;38;5;51m"
      r_med   = "\033[38;5;45m"
      r_dim   = "\033[38;5;39m"
      r_faint = "\033[38;5;25m"
    }

    num_raw = 0
  }
  {
    raw_lines[num_raw++] = $0
  }
  END {
    if (num_raw == 0) exit

    if (cols >= 101) {
      pad_left = int((cols - 101) / 2)
      crop_left = 0
    } else {
      pad_left = 0
      crop_left = int((101 - cols) / 2)
    }

    h_cycle = max_rows + 14

    for (r = 0; r < max_rows; r++) {
      src_idx = int((r * 64) / (max_rows > 1 ? max_rows - 1 : 1))
      line_txt = raw_lines[src_idx]
      line_len = length(line_txt)

      pct = int((r * 100) / (max_rows > 1 ? max_rows - 1 : 1))
      if (theme == "matrix" || theme == "green") {
        if (pct < 25)      s_col = "\033[1;38;5;46m"
        else if (pct < 50) s_col = "\033[38;5;40m"
        else if (pct < 75) s_col = "\033[38;5;34m"
        else               s_col = "\033[38;5;28m"
      } else if (theme == "crimson" || theme == "red") {
        if (pct < 25)      s_col = "\033[1;38;5;196m"
        else if (pct < 50) s_col = "\033[38;5;160m"
        else if (pct < 75) s_col = "\033[38;5;124m"
        else               s_col = "\033[38;5;88m"
      } else if (theme == "synthwave" || theme == "purple") {
        if (pct < 25)      s_col = "\033[1;38;5;201m"
        else if (pct < 50) s_col = "\033[38;5;165m"
        else if (pct < 75) s_col = "\033[38;5;129m"
        else               s_col = "\033[38;5;93m"
      } else if (theme == "amber" || theme == "gold") {
        if (pct < 25)      s_col = "\033[1;38;5;220m"
        else if (pct < 50) s_col = "\033[38;5;214m"
        else if (pct < 75) s_col = "\033[38;5;208m"
        else               s_col = "\033[38;5;172m"
      } else if (theme == "cobalt" || theme == "blue") {
        if (pct < 25)      s_col = "\033[1;38;5;39m"
        else if (pct < 50) s_col = "\033[38;5;33m"
        else if (pct < 75) s_col = "\033[38;5;27m"
        else               s_col = "\033[38;5;21m"
      } else if (theme == "mono") {
        s_col = ""
      } else {
        if (pct < 25)      s_col = "\033[1;38;5;51m"
        else if (pct < 50) s_col = "\033[38;5;45m"
        else if (pct < 75) s_col = "\033[38;5;39m"
        else               s_col = "\033[38;5;33m"
      }

      cur_c = ""
      row_out = ""

      for (c = 0; c < cols; c++) {
        skull_ch = " "
        if (cols >= 101) {
          if (c >= pad_left && (c - pad_left) < line_len) {
            skull_ch = substr(line_txt, (c - pad_left) + 1, 1)
          }
        } else {
          sc_idx = crop_left + c + 1
          if (sc_idx <= line_len) {
            skull_ch = substr(line_txt, sc_idx, 1)
          }
        }

        if (skull_ch != " " && skull_ch != "") {
          if (s_col != cur_c) {
            row_out = row_out s_col
            cur_c = s_col
          }
          row_out = row_out skull_ch
        } else {
          char_out = " "
          c_color = ""

          if (rain == 1) {
            col_spd = 1 + ((c * 7 + 3) % 2)
            col_off = (c * 19 + 7) % h_cycle
            col_len = 5 + ((c * 11) % 7)

            head_y = (step * col_spd + col_off) % h_cycle - 7
            dist = head_y - r

            if (dist >= 0 && dist <= col_len) {
              g_idx = ((r * 17 + c * 7 + step * 3) % g_len) + 1
              char_out = substr(glyphs, g_idx, 1)

              if (dist == 0)      c_color = r_head
              else if (dist <= 2) c_color = r_hi
              else if (dist <= 4) c_color = r_med
              else if (dist <= 6) c_color = r_dim
              else                c_color = r_faint
            }
          }

          if (c_color != cur_c) {
            if (c_color == "") row_out = row_out reset
            else               row_out = row_out c_color
            cur_c = c_color
          }
          row_out = row_out char_out
        }
      }

      if (cur_c != "") row_out = row_out reset
      print row_out
    }
  }' <<< "${RAW_FRAMES[frame_idx]}"
}

on_resize() {
  update_dimensions
  printf "\033[2J"
}
trap on_resize WINCH

THEMES=("cyan" "synthwave" "matrix" "crimson" "amber" "cobalt" "mono")
theme_idx=0

cycle_theme() {
  theme_idx=$(( (theme_idx + 1) % ${#THEMES[@]} ))
  COLOR_THEME="${THEMES[$theme_idx]}"
}

poll_key() {
  local dur="$1"
  local key=""

  if read -t "$dur" -n 1 key 2>/dev/null; then
    handle_key "$key"
    return
  fi
  local rc=$?
  if [ "$rc" -le 128 ] && [ "$rc" -ne 0 ]; then
    sleep "$dur" 2>/dev/null || sleep 1
  fi
}

handle_key() {
  local k="$1"
  case "$k" in
    q|Q|$'\e')
      cleanup
      ;;
    r|R)
      RAIN_ENABLED=$(( 1 - RAIN_ENABLED ))
      ;;
    g|G)
      if [ "$COLOR_THEME" = "matrix" ]; then
        COLOR_THEME="cyan"
      else
        COLOR_THEME="matrix"
      fi
      ;;
    c|C)
      cycle_theme
      ;;
    b|B)
      if [ "$MODE" = "bounce" ]; then
        MODE="loop"
      else
        MODE="bounce"
      fi
      ;;
    +|'=')
      DELAY=$(awk "BEGIN { d = $DELAY * 0.75; if (d < 0.02) d = 0.02; printf \"%.3f\", d }" 2>/dev/null || echo "0.05")
      ;;
    -|_)
      DELAY=$(awk "BEGIN { d = $DELAY * 1.35; if (d > 0.5) d = 0.5; printf \"%.3f\", d }" 2>/dev/null || echo "0.12")
      ;;
    h|H)
      SHOW_HUD=$(( 1 - SHOW_HUD ))
      if [ "$SHOW_HUD" -eq 0 ]; then
        printf "\033[%d;1H\033[K" "$ROWS"
      fi
      ;;
    ' ')
      while true; do
        local rk=""
        if read -n 1 rk 2>/dev/null; then
          if [ "$rk" = " " ]; then
            break
          elif [ "$rk" = "r" ] || [ "$rk" = "R" ]; then
            RAIN_ENABLED=$(( 1 - RAIN_ENABLED ))
            break
          elif [ "$rk" = "c" ] || [ "$rk" = "C" ]; then
            cycle_theme
            break
          elif [ "$rk" = "q" ] || [ "$rk" = "Q" ]; then
            cleanup
          fi
        else
          sleep 0.1
        fi
      done
      ;;
  esac
}

draw_hud() {
  local cur_f="$1"
  [ "$SHOW_HUD" -eq 0 ] && return

  local cur_fps
  cur_fps=$(awk "BEGIN { printf \"%.0f\", 1.0 / $DELAY }" 2>/dev/null || echo "$FPS")
  local r_status="ON"
  [ "$RAIN_ENABLED" -eq 0 ] && r_status="OFF"

  printf "\033[%d;1H" "$ROWS"
  if [ "$COLS" -lt 95 ]; then
    printf "${ESC}[1;38;5;51m⚡ ABLITERATED${RESET} ${ESC}[38;5;45m[%02d/14]${RESET} ${ESC}[38;5;39m[%s]${RESET} ${ESC}[38;5;46m[RAIN:%s]${RESET} ${ESC}[38;5;240m[R:rain C:color Q:quit]${RESET}${ESC}[K" \
      "$((cur_f + 1))" "$COLOR_THEME" "$r_status"
  else
    printf "${ESC}[38;5;238m───${RESET} ${ESC}[1;38;5;51m⚡ ABLITERATED${RESET} ${ESC}[38;5;244m//${RESET} ${ESC}[38;5;45mFRAME %02d/14${RESET} ${ESC}[38;5;244m//${RESET} ${ESC}[38;5;39m%-9s${RESET} ${ESC}[38;5;244m//${RESET} ${ESC}[38;5;46mRAIN: %-3s${RESET} ${ESC}[38;5;244m//${RESET} ${ESC}[38;5;33m%s FPS${RESET} ${ESC}[38;5;244m//${RESET} ${ESC}[38;5;240m[R]ain [C]olor [B]ounce [Q]uit${RESET}${ESC}[K" \
      "$((cur_f + 1))" "$COLOR_THEME" "$r_status" "$cur_fps"
  fi
}

main() {
  parse_args "$@"

  update_dimensions
  load_raw_frames

  for i in "${!THEMES[@]}"; do
    if [ "${THEMES[$i]}" = "$COLOR_THEME" ]; then
      theme_idx=$i
      break
    fi
  done

  # Switch to alternate screen buffer, hide cursor, disable line wrap
  printf "\033[?1049h\033[?25l\033[?7l\033[2J\033[1;1H"
  IN_ALT_SCREEN=1
  CURSOR_HIDDEN=1

  local tick=0
  local rainbow_step=0

  while true; do
    local seq=()
    if [ "$MODE" = "bounce" ]; then
      for ((i = 0; i < 14; i++)); do seq[${#seq[@]}]="$i"; done
      for ((i = 12; i > 0; i--)); do seq[${#seq[@]}]="$i"; done
    else
      for ((i = 0; i < 14; i++)); do seq[${#seq[@]}]="$i"; done
    fi

    for f in "${seq[@]}"; do
      # Render combined skull + matrix rain
      render_skull_matrix "$f" "$tick"

      # Draw HUD at bottom line
      draw_hud "$f"

      tick=$((tick + 1))
      poll_key "$DELAY"
    done

    if [ "$COLOR_THEME" = "rainbow" ]; then
      rainbow_step=$(( (rainbow_step + 1) % 6 ))
      case "$rainbow_step" in
        0) COLOR_THEME="cyan" ;;
        1) COLOR_THEME="synthwave" ;;
        2) COLOR_THEME="crimson" ;;
        3) COLOR_THEME="amber" ;;
        4) COLOR_THEME="matrix" ;;
        5) COLOR_THEME="cobalt" ;;
      esac
    fi

    [ "$MODE" = "once" ] && break
  done

  cleanup
}

